// Copies shared/logic.js to the backend and the website so both use identical calculations,
// and builds apps-script/SALIN-KE-APPS-SCRIPT.gs: Logic + Code in one file, in the right order,
// so it can be pasted into the Apps Script editor as a single Code.gs.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'shared', 'logic.js'), 'utf8');
const banner = '// GENERATED from shared/logic.js — edit that file, then run `node tools/sync-logic.js`.\n';
for (const target of ['apps-script/Logic.gs', 'assets/logic.js']) {
  fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  fs.writeFileSync(path.join(root, target), banner + src);
  console.log('wrote', target);
}
const code = fs.readFileSync(path.join(root, 'apps-script', 'Code.gs'), 'utf8');
const bundle =
  '// PCC Daily Report — backend lengkap. Tempel SELURUH isi file ini ke Code.gs di editor Apps Script.\n' +
  '// GENERATED by tools/sync-logic.js from shared/logic.js + apps-script/Code.gs. Jangan edit file ini langsung.\n\n' +
  src.replace(/\nif \(typeof module[^\n]*\n?$/, '\n') + '\n\n' + code;
fs.writeFileSync(path.join(root, 'apps-script', 'SALIN-KE-APPS-SCRIPT.gs'), bundle);
console.log('wrote apps-script/SALIN-KE-APPS-SCRIPT.gs');
